#Funcao do scape -> corrigir situacao em que voce quer colocar um texto entre aspas na string que ja tem aspas
#escape = pula o proximo caracter
print("Pedro \"Augusto\".")

#r -> para mostrar o escape
print(r"Pedro \"Augusto\".")

#jeito mais facil de fazer é simplemente iniciar com aspas simples e fechar com aspas simples ou vice-versa
print('Pedro "Augusto".')
print("Pedro 'Augusto'.")