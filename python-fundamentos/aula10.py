# PECULARIEDADES DO OPERADORES + E * 
'''
+ => concatenacao (somente string)
* => repeticao (string e int)
'''

concatenacao = 'A' + "b" + 'CD'
print(concatenacao)
print("Pedro" + " " + "Augusto") # ou print("Pedro " + " Augusto")

a_dez_vezes = "A" * 10 
tres_vezes_pedro = "Pedro" * 3

print(a_dez_vezes)
print(tres_vezes_pedro)